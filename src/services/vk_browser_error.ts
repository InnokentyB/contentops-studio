const knownCodes = new Set([
    '[VK_BROWSER_CONFIG_INVALID]', '[VK_BROWSER_JOB_INVALID]', '[VK_BROWSER_JOB_PERMISSIONS]',
    '[VK_BROWSER_MCP_TOKEN_REQUIRED]', '[VK_BROWSER_MCP_ENDPOINT_INVALID]',
    '[VK_BROWSER_MCP_RESPONSE_INVALID]', '[VK_BROWSER_MCP_CALL_FAILED]',
    '[VK_BROWSER_LOGIN_REQUIRED]', '[VK_BROWSER_CHALLENGE_REQUIRED]',
    '[VK_BROWSER_ASSET_UPLOAD_FAILED]', '[VK_BROWSER_READBACK_UNCONFIRMED]',
    '[VK_BROWSER_SUBMIT_AUTHORIZATION_REQUIRED]', '[VK_BROWSER_SUBMIT_UNCERTAIN]',
    '[VK_BROWSER_EXISTING_ATTEMPT_REQUIRES_RECONCILIATION]',
    '[VK_CLIP_UI_UNVERIFIED]', '[VK_CLIP_PROVIDER_EVIDENCE_REQUIRED]',
    '[VK_CLIP_BASELINE_UNCONFIRMED]', '[VK_CLIP_READBACK_UNCONFIRMED]',
    '[VK_CLIP_MEDIA_REQUIRED]', '[VK_CLIP_MP4_REQUIRED]', '[VK_CLIP_OPERATION_TIMEOUT]',
    '[VK_POST_BASELINE_REQUIRED]', '[VK_POST_BASELINE_UNCONFIRMED]', '[VK_POST_PROOF_INVALID]'
]);
/** Return only known operator codes; never echo a provider error message or opaque payload. */
export function vkBrowserErrorCode(error: unknown): string {
    const code = error instanceof Error ? /^\[[A-Z0-9_]+\]/.exec(error.message)?.[0] : null;
    return code && knownCodes.has(code) ? code : '[VK_BROWSER_OPERATION_FAILED]';
}
